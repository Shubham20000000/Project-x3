CREATE VIEW requests AS WITH ranked AS(SELECT *,ROW_NUMBER() OVER(PARTITION BY request_id ORDER BY row_id) AS rn FROM raw_requests)
SELECT request_id,external_ref,team_id,category_id,created_date,due_date,resolved_date,priority,channel,status FROM ranked WHERE rn=1;
CREATE VIEW eligible_requests AS SELECT * FROM requests WHERE resolved_date IS NOT NULL AND resolved_date>=created_date;
