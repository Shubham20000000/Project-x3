SELECT (SELECT COUNT(*) FROM raw_requests) AS raw_rows,COUNT(*) AS unique_rows FROM requests;
-- 2. Repeated business references: investigate rather than silently delete.
SELECT external_ref,COUNT(*) AS records FROM requests GROUP BY external_ref HAVING COUNT(*)>1;
-- 3. Invalid resolution dates.
SELECT * FROM requests WHERE resolved_date<created_date;
-- 4. Unknown teams.
SELECT r.request_id,r.team_id FROM requests r LEFT JOIN teams t ON r.team_id=t.team_id WHERE t.team_id IS NULL;
-- 5. KPI at team grain. Exclude open/invalid resolutions from denominator.
SELECT team_id,COUNT(*) AS eligible_resolutions,
SUM(CASE WHEN resolved_date>due_date THEN 1 ELSE 0 END) AS late_resolutions,
ROUND(100.0*SUM(CASE WHEN resolved_date>due_date THEN 1 ELSE 0 END)/NULLIF(COUNT(*),0),2) AS late_percent,
ROUND(AVG(julianday(resolved_date)-julianday(created_date)),2) AS mean_resolution_days
FROM eligible_requests GROUP BY team_id;
